"""HTML report renderer (stdlib-only).

The HTML report is the primary visual deliverable: print-friendly CSS
(``@page`` rules, page-break hints) means any browser's *Print → Save as
PDF* produces the one-page site report with no extra dependencies. This is
the default PDF path; ``alerts/pdf.py`` offers an optional reportlab
upgrade.

Output is deterministic: same report in, same bytes out.
"""

from __future__ import annotations

import html as _html
from typing import Dict, List

from .model import SiteReport
from .reader import AlertRecord

_SEVERITY_COLORS = {
    "critical": "#b91c1c",
    "warning": "#b45309",
    "info": "#1d4ed8",
}

_CSS = """
@page { size: A4; margin: 18mm 15mm; }
* { box-sizing: border-box; }
body { font-family: Helvetica, Arial, sans-serif; color: #1f2937;
       margin: 0; font-size: 11pt; line-height: 1.45; }
header { border-bottom: 3px solid #111827; padding-bottom: 8px;
         margin-bottom: 12px; }
header h1 { margin: 0 0 2px 0; font-size: 20pt; }
header .sub { color: #6b7280; font-size: 9pt; }
.headline { font-size: 13pt; font-weight: bold; margin: 10px 0; }
.badges { margin: 8px 0; }
.badge { display: inline-block; border-radius: 4px; color: #fff;
         font-size: 9pt; font-weight: bold; padding: 2px 10px;
         margin-right: 6px; }
table { width: 100%; border-collapse: collapse; margin: 10px 0;
        font-size: 9.5pt; page-break-inside: auto; }
th, td { border: 1px solid #d1d5db; padding: 5px 7px; text-align: left; }
th { background: #f3f4f6; }
tr { page-break-inside: avoid; }
.sev { font-weight: bold; }
ul.summary { padding-left: 18px; }
ul.summary li { margin-bottom: 4px; }
footer { margin-top: 14px; border-top: 1px solid #d1d5db; padding-top: 6px;
         color: #6b7280; font-size: 8.5pt; }
@media print { .noprint { display: none; } }
"""


def _esc(value: object) -> str:
    return _html.escape("" if value is None else str(value))


def _fmt(value: object) -> str:
    if value is None:
        return "n/a"
    try:
        return f"{float(value):.3f}"  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return _esc(value)


def _badge(severity: str, count: int) -> str:
    color = _SEVERITY_COLORS.get(severity, "#374151")
    return (f'<span class="badge" style="background:{color}">'
            f"{_esc(severity.upper())}: {count}</span>")


def _row(record: AlertRecord) -> str:
    color = _SEVERITY_COLORS.get(record.severity, "#374151")
    return (
        "<tr>"
        f'<td class="sev" style="color:{color}">{_esc(record.severity.upper())}</td>'
        f"<td>{_esc(record.index.upper())}</td>"
        f"<td>{_esc(record.metric)}</td>"
        f"<td>{_fmt(record.value)}</td>"
        f"<td>{_fmt(record.delta)}</td>"
        f"<td>{_fmt(record.z_score)}</td>"
        f"<td>{_esc(record.threshold_kind)} {_fmt(record.threshold)}</td>"
        f"<td>{_esc(record.pass_date)}</td>"
        "</tr>"
    )


def render_html(report: SiteReport) -> str:
    """Render a :class:`SiteReport` as a self-contained HTML document."""
    badges = " ".join(
        _badge(sev, count)
        for sev, count in report.by_severity.items() if count
    )
    rows = "\n".join(_row(r) for r in report.events)
    summary_items = "\n".join(
        f"<li>{_esc(line)}</li>" for line in report.summary_lines
    )
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Site alert report — {_esc(report.site_name)}</title>
<style>{_CSS}</style>
</head>
<body>
<header>
  <h1>Site alert report</h1>
  <div class="sub">{_esc(report.site_name)} &middot; site id
  <code>{_esc(report.site_id)}</code> &middot; generated
  {_esc(report.generated_at)} &middot; report <code>{_esc(report.report_id)}</code></div>
</header>
<p class="headline">{_esc(report.headline)}</p>
<div class="badges">{badges}</div>
<h2>What changed</h2>
<ul class="summary">
{summary_items}
</ul>
<h2>Alert detail</h2>
<table>
  <thead><tr><th>Severity</th><th>Index</th><th>Metric</th><th>Value</th>
  <th>&Delta;</th><th>z-score</th><th>Threshold</th><th>Pass date</th></tr></thead>
  <tbody>
{rows}
  </tbody>
</table>
<footer>
  Generated by <b>survey-alerts</b> (earthwatch-suite) from
  <code>alerts.jsonl</code> written by survey-monitor. Alert semantics:
  <b>critical</b> = needs eyes today; <b>warning</b> = needs review;
  <b>info</b> = approaching a threshold (watch only).
</footer>
</body>
</html>
"""


def render_text(report: SiteReport) -> str:
    """Render a :class:`SiteReport` as plain text (email fallback, logs)."""
    lines: List[str] = [
        f"Site alert report — {report.site_name} ({report.site_id})",
        f"Generated {report.generated_at} · report {report.report_id}",
        "",
        report.headline,
        "",
    ]
    sev = ", ".join(f"{k}: {v}" for k, v in report.by_severity.items() if v)
    lines.append(f"By severity — {sev}" if sev else "No alerts.")
    lines.append("")
    lines.append("What changed:")
    for line in report.summary_lines:
        lines.append(f"  • {line}")
    lines.append("")
    lines.append("Alert detail:")
    header = (f"  {'SEVERITY':<9}{'INDEX':<7}{'METRIC':<8}{'VALUE':>8}"
              f"{'DELTA':>9}{'Z':>8}  {'THRESHOLD':<22}{'PASS DATE'}")
    lines.append(header)
    for r in report.events:
        thr = f"{r.threshold_kind} {r.threshold if r.threshold is not None else 'n/a'}"
        lines.append(
            f"  {r.severity.upper():<9}{r.index.upper():<7}"
            f"{(r.metric or ''):<8}"
            f"{_fmt(r.value):>8}{_fmt(r.delta):>9}{_fmt(r.z_score):>8}  "
            f"{thr:<22}{r.pass_date}")
    lines.append("")
    lines.append("Generated by survey-alerts (earthwatch-suite).")
    return "\n".join(lines)

def site_reports_by_site(reports: Dict[str, SiteReport]) -> List[SiteReport]:
    """Order multi-site reports deterministically (worst site first)."""
    rank = {"critical": 2, "warning": 1, "info": 0}
    return sorted(
        reports.values(),
        key=lambda r: (-rank.get(r.worst or "info", 0), r.site_id))
