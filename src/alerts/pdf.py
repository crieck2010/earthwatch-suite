"""Optional native-PDF rendering via reportlab (lazy import).

The default PDF path needs no dependency at all: render HTML with
``alerts.html.render_html`` and use any browser's *Print → Save as PDF*.
This module is the upgrade path — a real one-page PDF built with reportlab,
activated only when reportlab is installed::

    pip install "survey-alerts[pdf]"

Importing this module without reportlab raises :class:`AlertsError` with a
helpful message; the HTML path always works.
"""

from __future__ import annotations

import os
from typing import List

from .errors import AlertsError
from .model import SiteReport


def _require_reportlab():
    try:
        from reportlab.lib import colors  # noqa: F401
        from reportlab.lib.pagesizes import A4  # noqa: F401
        from reportlab.lib.styles import getSampleStyleSheet  # noqa: F401
        from reportlab.platypus import (  # noqa: F401
            Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle)
    except ImportError as exc:
        raise AlertsError(
            "native PDF rendering needs reportlab: "
            'pip install "survey-alerts[pdf]" — or render HTML with '
            "'survey-alerts render --format html' and print to PDF") from exc
    import reportlab.lib.colors as colors
    import reportlab.lib.pagesizes as pagesizes
    import reportlab.lib.styles as styles
    import reportlab.platypus as platypus
    return colors, pagesizes, styles, platypus


_SEVERITY_HEX = {"critical": "#b91c1c", "warning": "#b45309", "info": "#1d4ed8"}


def _fmt(value: object) -> str:
    if value is None:
        return "n/a"
    try:
        return f"{float(value):.3f}"  # type: ignore[arg-type]
    except (TypeError, ValueError):
        return str(value)


def render_pdf(report: SiteReport, path: str) -> str:
    """Render ``report`` to a one-page-ish PDF at ``path``.

    Returns ``path``. Raises :class:`AlertsError` if reportlab is missing.
    Deterministic for identical input (modulo PDF metadata timestamps,
    which reportlab does not let us pin without deep hacks — byte equality
    across runs is *not* guaranteed; content equality is).
    """
    colors, pagesizes, styles, platypus = _require_reportlab()
    directory = os.path.dirname(os.path.abspath(path))
    os.makedirs(directory, exist_ok=True)

    sheet = styles.getSampleStyleSheet()
    title_style = sheet["Title"]
    heading_style = sheet["Heading2"]
    body_style = sheet["BodyText"]

    story: List = [
        platypus.Paragraph(f"Site alert report — {report.site_name}",
                           title_style),
        platypus.Paragraph(
            f"Site <b>{report.site_id}</b> · generated {report.generated_at} "
            f"· report <b>{report.report_id}</b>", body_style),
        platypus.Spacer(1, 8),
        platypus.Paragraph(f"<b>{report.headline}</b>", body_style),
        platypus.Spacer(1, 8),
        platypus.Paragraph("What changed", heading_style),
    ]
    for line in report.summary_lines:
        story.append(platypus.Paragraph(f"• {line}", body_style))
    story.append(platypus.Spacer(1, 8))
    story.append(platypus.Paragraph("Alert detail", heading_style))

    header = ["Severity", "Index", "Metric", "Value", "Δ", "z", "Threshold",
              "Pass date"]
    rows = [header]
    for r in report.events:
        rows.append([
            r.severity.upper(), r.index.upper(), r.metric or "",
            _fmt(r.value), _fmt(r.delta), _fmt(r.z_score),
            f"{r.threshold_kind} {_fmt(r.threshold)}", r.pass_date,
        ])
    table = platypus.Table(rows, repeatRows=1)
    table.setStyle(platypus.TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f3f4f6")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#d1d5db")),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(table)
    story.append(platypus.Spacer(1, 10))
    story.append(platypus.Paragraph(
        "Generated by <b>survey-alerts</b> (earthwatch-suite) from "
        "<i>alerts.jsonl</i> written by survey-monitor.",
        sheet["Normal"]))

    doc = platypus.SimpleDocTemplate(
        path, pagesize=pagesizes.A4,
        leftMargin=36, rightMargin=36, topMargin=36, bottomMargin=36,
        title=f"Site alert report — {report.site_name}",
        author="survey-alerts")
    doc.build(story)
    return path


def pdf_available() -> bool:
    """True when reportlab is importable."""
    try:
        import reportlab  # noqa: F401
    except ImportError:
        return False
    return True
